export type Lang = "en" | "zh";

let currentLang: Lang = "zh";

export function getLang(): Lang {
  return currentLang;
}

export function toggleLang(): Lang {
  currentLang = currentLang === "en" ? "zh" : "en";
  return currentLang;
}

